def _add(document: Document, text: str, style: str | None = None) -> None:
    paragraph = document.add_paragraph(text, style=style) if style else document.add_paragraph(text)
    for run in paragraph.runs:
        run.font.size = Pt(10.5)


def build() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    manifest = {"documents": []}
    for topic in DOCS:
        document = Document()
        document.add_heading(topic["title"], level=0)
        _add(document, f"文档类别：{topic['category']}　适用范围：制造企业工业物资采购")
        _add(document, topic["summary"])
        for heading, body in topic["sections"]:
            document.add_heading(heading, level=1)
            _add(document, body)
        if topic["sources"]:
            document.add_heading("参考资料", level=1)
            for key in topic["sources"]:
                _add(document, f"- {SOURCES[key]}")
        path = OUT / topic["file"]
        document.save(path)
        manifest["documents"].append(
            {
                "file": topic["file"],
                "title": topic["title"],
                "category": topic["category"],
                "summary": topic["summary"],
                "tags": topic["tags"],
                "sources": [SOURCES[key] for key in topic["sources"]],
            }
        )
    (OUT / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"generated {len(DOCS)} documents in {OUT}")


if __name__ == "__main__":
    build()
